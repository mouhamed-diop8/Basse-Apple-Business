type SpecTuple = [label: string, value: string];
type ColorTuple = [name: string, hex: string];
/** [libellé, supplément de prix, stock] */
type VariantTuple = [value: string, priceDelta: number, stock: number];

interface Draft {
  id: string;
  name: string;
  brand: string;
  category_id: string;
  price: number;
  sale_price?: number;
  stock: number;
  rating: number;
  reviews_count: number;
  units_sold: number;
  age: number;
  description: string;
  specs: SpecTuple[];
  condition?: ProductCondition;
  featured?: boolean;
  warranty?: string;
  threshold?: number;
  storage_gb?: number;
  ram_gb?: number;
  screen_inches?: number;
  colors?: ColorTuple[];
  storages?: VariantTuple[];
  rams?: VariantTuple[];
  configs?: VariantTuple[];
  accessories?: string[];
  images?: string[];
}

const buildVariants = (
  productId: string,
  kind: VariantKind,
  name: string,
  tuples: VariantTuple[] | undefined,
  hexes?: ColorTuple[],
): ProductVariant[] => {
  if (!tuples) return [];
  return tuples.map(([value, priceDelta, stock], index) => ({
    id: `${productId}-${kind}-${index}`,
    product_id: productId,
    kind,
    name,
    value,
    price_delta: cfa(priceDelta),
    stock,
    hex: hexes?.find(([label]) => label === value)?.[1] ?? null,
  }));
};

const make = (draft: Draft): Product => {
  const specs: SpecEntry[] = draft.specs.map(([label, value]) => ({ label, value }));
  const colorTuples = draft.colors ?? [];

  // Les coloris sont répartis sur le stock global : ils ne changent pas le prix.
  const colorVariants = buildVariants(
    draft.id,
    'color',
    'Couleur',
    colorTuples.map<VariantTuple>(([label], index) => [
      label,
      0,
      Math.max(0, Math.round(draft.stock / Math.max(1, colorTuples.length)) + (index === 0 ? draft.stock % Math.max(1, colorTuples.length) : 0)),
    ]),
    colorTuples,
  );

  return {
    id: draft.id,
    name: draft.name,
    description: draft.description,
    brand: draft.brand,
    category_id: draft.category_id,
    price: cfa(draft.price),
    sale_price: draft.sale_price != null ? cfa(draft.sale_price) : null,
    stock: draft.stock,
    low_stock_threshold: draft.threshold ?? 5,
    sku: draft.id.toUpperCase().replace(/-/g, '-'),
    warranty: draft.warranty ?? '12 mois garantie boutique',
    condition: draft.condition ?? 'new',
    rating: draft.rating,
    reviews_count: draft.reviews_count,
    units_sold: draft.units_sold,
    is_active: true,
    is_featured: draft.featured ?? false,
    return_policy: 'Retour sous 14 jours, produit non ouvert, avec le billet de commande.',
    shipping_note: 'Expédié depuis Dakar (Keur Massar). Suivi WhatsApp inclus.',
    included_accessories: draft.accessories ?? [],
    specs,
    storage_gb: draft.storage_gb ?? null,
    ram_gb: draft.ram_gb ?? null,
    screen_inches: draft.screen_inches ?? null,
    colors: colorTuples.map(([label]) => label),
    images: draft.images ?? [],
    variants: [
      ...colorVariants,
      ...buildVariants(draft.id, 'storage', 'Stockage', draft.storages),
      ...buildVariants(draft.id, 'ram', 'Mémoire', draft.rams),
      ...buildVariants(draft.id, 'config', 'Configuration', draft.configs),
    ],
    created_at: daysAgo(draft.age),
  };
};

